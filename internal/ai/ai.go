var (
	ErrConsentRequired = errors.New("privacy protection: remote AI calls require explicit user consent")
	ErrNoAPIKey        = errors.New("missing API key for remote AI provider")
)

// Config holds AI engine settings.
type Config struct {
	Provider       string // "ollama", "openai", "anthropic", "offline"
	Model          string
	BaseURL        string
	APIKey         string
	AllowRemoteAI  bool   // Privacy gate
	TimeoutSeconds int
}

// DefaultConfig returns safe local-first defaults.
func DefaultConfig() Config {
	prov := "offline"
	if os.Getenv("OLLAMA_HOST") != "" || os.Getenv("OLLAMA_MODEL") != "" {
		prov = "ollama"
	}
	return Config{
		Provider:       prov,
		Model:          "llama3.2",
		BaseURL:        "http://localhost:11434",
		AllowRemoteAI:  false, // Opt-in required
		TimeoutSeconds: 30,
	}
}

// Client executes queries against configured AI backends.
type Client struct {
	cfg        Config
	httpClient *http.Client
}

// NewClient creates an AI client.
func NewClient(cfg Config) *Client {
	if cfg.TimeoutSeconds <= 0 {
		cfg.TimeoutSeconds = 30
	}
	return &Client{
		cfg: cfg,
		httpClient: &http.Client{
			Timeout: time.Duration(cfg.TimeoutSeconds) * time.Second,
		},
	}
}

// QueryCodebase answers developer questions about code structure, relationships, or changes.
func (c *Client) QueryCodebase(ctx context.Context, req model.AIQueryRequest, syms []model.Symbol, rels []model.Relationship, stats *model.RepoScanStats) (*model.AIQueryResponse, error) {
	provider := req.Provider
	if provider == "" {
		provider = c.cfg.Provider
	}

	// Privacy check
	if (provider == "openai" || provider == "anthropic") && !req.UserConsent && !c.cfg.AllowRemoteAI {
		return nil, ErrConsentRequired
	}

	// Retrieve relevant context from static knowledge graph
	relevantSyms, relevantRels := retrieveContext(req.Query, syms, rels)

	// If provider is remote or ollama, call the model
	if provider == "ollama" {
		ans, err := c.callOllama(ctx, req.Query, relevantSyms, relevantRels, stats)
		if err == nil && ans != "" {
			return &model.AIQueryResponse{
				Answer:     ans,
				Confidence: 0.9,
				Provider:   "ollama",
			}, nil
		}
	} else if provider == "openai" && (req.UserConsent || c.cfg.AllowRemoteAI) {
		ans, err := c.callOpenAI(ctx, req.Query, relevantSyms, relevantRels, stats)
		if err == nil && ans != "" {
			return &model.AIQueryResponse{
				Answer:     ans,
				Confidence: 0.95,
				Provider:   "openai",
			}, nil
		}
	}

	// Fallback to deterministic AST / graph synthesis (fast, zero hallucinations, completely offline)
	answer, refs := synthesizeDeterministicAnswer(req.Query, relevantSyms, relevantRels, stats)
	return &model.AIQueryResponse{
		Answer:     answer,
		SourceRefs: refs,
		Confidence: 1.0, // High confidence: derived directly from AST facts
		Provider:   "deterministic-engine",
	}, nil
}

// GenerateContext creates structured context exports for AI tools (Claude Code, Cursor, Codex).
func GenerateContext(format string, repoName string, files []model.FileNode, syms []model.Symbol, rels []model.Relationship, stats *model.RepoScanStats) string {
	var sb strings.Builder

	switch strings.ToLower(format) {
	case "cursor", ".cursorrules":
		sb.WriteString("# CodeDNA Architecture & System Guidelines for Cursor\n")
		sb.WriteString(fmt.Sprintf("# Repository: %s\n\n", repoName))
		sb.WriteString("## Project Overview\n")
		if stats != nil {
			sb.WriteString(fmt.Sprintf("- Total Files: %d\n", stats.FilesParsed))
			sb.WriteString(fmt.Sprintf("- Total LOC: %d\n", stats.LOC))
			if len(stats.Frameworks) > 0 {
				sb.WriteString(fmt.Sprintf("- Frameworks: %s\n", strings.Join(stats.Frameworks, ", ")))
			}
		}
		sb.WriteString("\n## Key Architectural Modules & Symbols\n")
		for i, s := range topSymbolsByComplexity(syms, 15) {
			sb.WriteString(fmt.Sprintf("- `%s` (%s:%d) [kind=%s, complexity=%d]\n", s.QualifiedName, s.File, s.Line, s.Kind, s.Complexity))
			_ = i
		}
		sb.WriteString("\n## Dependency Call Rules\n")
		sb.WriteString("- Respect architectural boundaries and maintain low coupling between modules.\n")
		sb.WriteString("- Avoid circular imports.\n")

	case "claude", "claude.md":
		sb.WriteString(fmt.Sprintf("# CLAUDE.md - Codebase Intelligence for %s\n\n", repoName))
		sb.WriteString("> Generated by CodeDNA 2.0 Static Intelligence Engine\n\n")
		sb.WriteString("## Repository Architecture\n")
		if stats != nil {
			sb.WriteString(fmt.Sprintf("- **Languages**: %v\n", stats.Languages))
			sb.WriteString(fmt.Sprintf("- **Frameworks**: %v\n", stats.Frameworks))
			sb.WriteString(fmt.Sprintf("- **Parsed Symbols**: %d\n", stats.SymbolsFound))
			sb.WriteString(fmt.Sprintf("- **Resolved Relationships**: %d\n\n", stats.ResolvedCalls))
		}
		sb.WriteString("## Important Entrypoints & High-Complexity Nodes\n")
		for _, s := range topSymbolsByComplexity(syms, 20) {
			sb.WriteString(fmt.Sprintf("- `%s` in [`%s#L%d`](%s) - %s (Complexity: %d)\n", s.QualifiedName, s.File, s.Line, s.File, s.Kind, s.Complexity))
		}
		sb.WriteString("\n## Key Call Chains\n")
		count := 0
		for _, r := range rels {
			if r.Confidence >= 0.8 && r.ToID != "" {
				sb.WriteString(fmt.Sprintf("- `%s` calls `%s` (%s)\n", r.FromID, r.ToID, r.Method))
				count++
				if count >= 20 {
					break
				}
			}
		}

	default: // markdown export
		sb.WriteString(fmt.Sprintf("# CodeDNA Context Snapshot: %s\n\n", repoName))
		if stats != nil {
			sb.WriteString(fmt.Sprintf("- Files: %d | LOC: %d | Symbols: %d | Edges: %d\n\n", stats.FilesParsed, stats.LOC, stats.SymbolsFound, stats.Relationships))
		}
		sb.WriteString("### Core Symbols\n")
		for _, s := range topSymbolsByComplexity(syms, 25) {
			sb.WriteString(fmt.Sprintf("- **%s** (`%s`): %s (line %d, complexity %d)\n", s.QualifiedName, s.Kind, s.File, s.Line, s.Complexity))
		}
	}

	return sb.String()
}

// MapBusinessLogic classifies files and symbols into functional business modules.
func MapBusinessLogic(files []model.FileNode, syms []model.Symbol) []model.BusinessLogicModule {
	domainKeywords := map[string][]string{
		"Authentication & Authorization": {"auth", "login", "jwt", "session", "user", "oauth", "password", "token", "permission"},
		"Payment & Billing":              {"pay", "payment", "billing", "invoice", "stripe", "checkout", "transaction", "refund", "card"},
		"Order & Cart Management":        {"order", "cart", "item", "basket", "checkout", "purchase", "fulfillment"},
		"User & Profile Management":      {"user", "profile", "account", "customer", "member", "identity"},
		"API & Routing Layer":            {"handler", "controller", "router", "endpoint", "api", "route", "serve"},
		"Database & Persistence Layer":   {"store", "repo", "repository", "model", "migration", "schema", "db", "dao"},
		"Notification & Messaging":       {"notify", "notification", "email", "sms", "webhook", "queue", "worker", "event"},
	}

	moduleMap := make(map[string]*model.BusinessLogicModule)

	for domain, keywords := range domainKeywords {
		var matchedFiles []string
		var matchedSyms []string

		for _, f := range files {
			lowerPath := strings.ToLower(f.Path)
			for _, kw := range keywords {
				if strings.Contains(lowerPath, kw) {
					matchedFiles = append(matchedFiles, f.Path)
					break
				}
			}
		}

		for _, s := range syms {
			lowerName := strings.ToLower(s.Name)
			lowerFile := strings.ToLower(s.File)
			for _, kw := range keywords {
				if strings.Contains(lowerName, kw) || strings.Contains(lowerFile, kw) {
					matchedSyms = append(matchedSyms, s.QualifiedName+" ("+s.File+")")
					break
				}
			}
		}

		if len(matchedFiles) > 0 || len(matchedSyms) > 0 {
			conf := 0.85
			if len(matchedFiles) > 2 && len(matchedSyms) > 2 {
				conf = 0.95
			}
			moduleMap[domain] = &model.BusinessLogicModule{
				Domain:      domain,
				Description: fmt.Sprintf("Domain handling %s across %d files and %d discovered symbols.", strings.ToLower(domain), len(matchedFiles), len(matchedSyms)),
				Files:       uniqueStrings(matchedFiles),
				KeySymbols:  uniqueStrings(matchedSyms[:min(len(matchedSyms), 10)]),
				Confidence:  conf,
			}
		}
	}

	var results []model.BusinessLogicModule
	for _, m := range moduleMap {
		results = append(results, *m)
	}
	sort.Slice(results, func(i, j int) bool {
		return results[i].Domain < results[j].Domain
	})

	return results
}

func retrieveContext(query string, syms []model.Symbol, rels []model.Relationship) ([]model.Symbol, []model.Relationship) {
	qLower := strings.ToLower(query)
	var matchedSyms []model.Symbol
	matchedIDs := make(map[string]bool)

	for _, s := range syms {
		if strings.Contains(strings.ToLower(s.Name), qLower) || strings.Contains(strings.ToLower(s.File), qLower) {
			matchedSyms = append(matchedSyms, s)
			matchedIDs[s.ID] = true
		}
	}

	var matchedRels []model.Relationship
	for _, r := range rels {
		if matchedIDs[r.FromID] || matchedIDs[r.ToID] || strings.Contains(strings.ToLower(r.ToName), qLower) {
			matchedRels = append(matchedRels, r)
		}
	}

	return matchedSyms, matchedRels
}

func synthesizeDeterministicAnswer(query string, syms []model.Symbol, rels []model.Relationship, stats *model.RepoScanStats) (string, []model.Ref) {
	var sb strings.Builder
	var refs []model.Ref

	sb.WriteString(fmt.Sprintf("### CodeDNA Static Analysis for: \"%s\"\n\n", query))

	if len(syms) == 0 {
		sb.WriteString("No exact symbols matched the query keyword directly. Below is the repository structural summary:\n\n")
		if stats != nil {
			sb.WriteString(fmt.Sprintf("- Total Files: %d\n- Total LOC: %d\n- Languages: %v\n- Frameworks: %v\n", stats.FilesParsed, stats.LOC, stats.Languages, stats.Frameworks))
		}
		return sb.String(), refs
	}

	sb.WriteString(fmt.Sprintf("Found **%d relevant symbols**:\n\n", len(syms)))
	for i, s := range syms {
		if i >= 10 {
			sb.WriteString(fmt.Sprintf("- ... and %d more symbols.\n", len(syms)-10))
			break
		}
		sb.WriteString(fmt.Sprintf("- **`%s`** (`%s` in `%s` line %d) - Complexity: %d\n", s.QualifiedName, s.Kind, s.File, s.Line, s.Complexity))
		refs = append(refs, model.Ref{File: s.File, Line: s.Line, Col: s.Column})
	}

	if len(rels) > 0 {
		sb.WriteString("\n**Discovered Call Relationships**:\n\n")
		for i, r := range rels {
			if i >= 10 {
				break
			}
			sb.WriteString(fmt.Sprintf("- `%s` -> `%s` (confidence: %.2f, method: %s)\n", r.FromID, r.ToName, r.Confidence, r.Method))
		}
	}

	return sb.String(), refs
}

func (c *Client) callOllama(ctx context.Context, prompt string, syms []model.Symbol, rels []model.Relationship, stats *model.RepoScanStats) (string, error) {
	url := c.cfg.BaseURL + "/api/generate"
	payload := map[string]interface{}{
		"model":  c.cfg.Model,
		"prompt": fmt.Sprintf("Context: Repository with %d symbols. Question: %s", len(syms), prompt),
		"stream": false,
	}
	body, _ := json.Marshal(payload)
	req, err := http.NewRequestWithContext(ctx, "POST", url, bytes.NewReader(body))
	if err != nil {
		return "", err
	}
	req.Header.Set("Content-Type", "application/json")
	resp, err := c.httpClient.Do(req)
	if err != nil {
		return "", err
	}
	defer resp.Body.Close()

	var result struct {
		Response string `json:"response"`
	}
	if err := json.NewDecoder(resp.Body).Decode(&result); err != nil {
		return "", err
	}
	return result.Response, nil
}

func (c *Client) callOpenAI(ctx context.Context, prompt string, syms []model.Symbol, rels []model.Relationship, stats *model.RepoScanStats) (string, error) {
	apiKey := c.cfg.APIKey
	if apiKey == "" {
		apiKey = os.Getenv("OPENAI_API_KEY")
	}
	if apiKey == "" {
		return "", ErrNoAPIKey
	}

	baseURL := c.cfg.BaseURL
	if baseURL == "" || baseURL == "http://localhost:11434" {
		baseURL = "https://api.openai.com/v1"
	}
	url := baseURL + "/chat/completions"

	messages := []map[string]string{
		{"role": "system", "content": "You are CodeDNA Codebase Assistant. Answer questions accurately based on provided symbol and relationship facts."},
		{"role": "user", "content": fmt.Sprintf("Codebase context:\nSymbols: %d\nQuery: %s", len(syms), prompt)},
	}

	payload := map[string]interface{}{
		"model":    "gpt-4o-mini",
		"messages": messages,
	}
	body, _ := json.Marshal(payload)

	req, err := http.NewRequestWithContext(ctx, "POST", url, bytes.NewReader(body))
	if err != nil {
		return "", err
	}
	req.Header.Set("Content-Type", "application/json")
	req.Header.Set("Authorization", "Bearer "+apiKey)

	resp, err := c.httpClient.Do(req)
	if err != nil {
		return "", err
	}
	defer resp.Body.Close()

	if resp.StatusCode >= 400 {
		b, _ := io.ReadAll(resp.Body)
		return "", fmt.Errorf("openai error: %s", string(b))
	}

	var result struct {
		Choices []struct {
			Message struct {
				Content string `json:"content"`
			} `json:"message"`
		} `json:"choices"`
	}
	if err := json.NewDecoder(resp.Body).Decode(&result); err != nil {
		return "", err
	}
	if len(result.Choices) > 0 {
		return result.Choices[0].Message.Content, nil
	}
	return "", nil
}

func topSymbolsByComplexity(syms []model.Symbol, top int) []model.Symbol {
	cp := append([]model.Symbol(nil), syms...)
	sort.Slice(cp, func(i, j int) bool {
		return cp[i].Complexity > cp[j].Complexity
	})
	if len(cp) > top {
		cp = cp[:top]
	}
	return cp
}

func uniqueStrings(in []string) []string {
	seen := make(map[string]bool)
	var out []string
	for _, s := range in {
		if !seen[s] {
			seen[s] = true
			out = append(out, s)
		}
	}
	return out
}

func min(a, b int) int {
	if a < b {
		return a
	}
	return b
}
